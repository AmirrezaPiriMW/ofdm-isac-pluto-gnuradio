#!/usr/bin/env python3
"""Build the README results table from results/metrics.json and insert it between the
RESULTS markers in README.md, so that every number in the README comes from the data."""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    m = json.loads((ROOT / "results/metrics.json").read_text())
    ind, out, two = m["indoor"], m["outdoor"], m["two_device"]
    w, u, p = ind["walker"], out["uav"], out["person"]
    tc = two["cases"]
    best = tc["two Plutos, CFO + direct-path referencing"]
    rows = [
        "| Scenario | Quantity | Truth | Estimate | Error |",
        "|---|---|---|---|---|",
        f"| Indoor, person walking | torso Doppler | {ind['walker_truth']['doppler_hz']:.2f} Hz | {w['doppler_hz']:.2f} Hz | "
        f"{w['doppler_error_hz']:+.3f} Hz ({w['doppler_error_cells']:+.3f} cells) |",
        f"| Indoor, desk fan (3 blades, 1200 rpm) | rotor line spacing | {ind['fan_blade_rate_true_hz']:.1f} Hz | "
        f"{ind['fan_blade_rate_est_hz']:.2f} Hz | {ind['fan_blade_rate_est_hz'] - ind['fan_blade_rate_true_hz']:+.2f} Hz |",
        f"| Indoor | communication on the same CPI | BER 0 | BER {ind['ber']:.0e} over {ind['n_bits']:,} bits, "
        f"EVM {ind['evm_db']:.1f} dB | |",
        f"| Outdoor, UAV body | excess range-sum | {out['uav_truth']['excess_range_m']:.2f} m | {u['excess_range_m']:.2f} m | "
        f"{u['excess_range_error_m']:+.2f} m ({u['excess_range_error_m'] / m['numerology']['outdoor_uav']['range_sum_resolution']:+.3f} cells) |",
        f"| Outdoor, UAV body | Doppler | {out['uav_truth']['doppler_hz']:.2f} Hz | {u['doppler_hz']:.2f} Hz | "
        f"{u['doppler_error_hz']:+.2f} Hz ({u['doppler_error_cells']:+.3f} cells) |",
        f"| Outdoor, UAV rotors (4 x 2 blades) | rotor line spacing | {min(out['uav_blade_rates_true_hz']):.1f} to "
        f"{max(out['uav_blade_rates_true_hz']):.1f} Hz | {out['uav_blade_rate_est_hz']:.1f} Hz | inside the true spread |",
        f"| Outdoor, person (slow, 0.5 cell) | Doppler | {out['person_truth']['doppler_hz']:.2f} Hz | {p['doppler_hz']:.2f} Hz | "
        f"{p['doppler_error_hz']:+.2f} Hz (zero-Doppler notch bias) |",
        f"| Outdoor | communication | BER 0 | BER {out['ber']:.0e} over {out['n_bits']:,} bits, EVM {out['evm_db']:.1f} dB | |",
        f"| Two Plutos (2 ppm, CFO {two['cfo_true_hz']:.0f} Hz) | CFO estimate | {two['cfo_true_hz']:.1f} Hz | "
        f"{best['cfo_est_hz']:.2f} Hz | {best['cfo_est_hz'] - two['cfo_true_hz']:+.3f} Hz |",
        f"| Two Plutos, no correction | link / walker | | BER {tc['two Plutos, no correction']['ber']:.2f}, walker "
        f"{'detected' if tc['two Plutos, no correction']['walker']['detected'] else 'missed'} | |",
    ]
    co = tc["two Plutos, CFO correction only"]["walker"]
    if co.get("detected"):
        rows.append(f"| Two Plutos, CFO only (SFO uncorrected) | walker excess range | "
                    f"{two['walker_truth']['excess_range_m']:.2f} m | {co['excess_range_m']:.1f} m | "
                    f"{co['excess_range_error_m']:+.1f} m |")
    rows.append(f"| Two Plutos, CFO + direct-path referencing | walker Doppler | {two['walker_truth']['doppler_hz']:.2f} Hz | "
                f"{best['walker']['doppler_hz']:.2f} Hz | {best['walker']['doppler_error_hz']:+.3f} Hz, BER {best['ber']:.0e} |")
    if "monte_carlo_uav" in m:
        mc = m["monte_carlo_uav"]
        pd = ", ".join(f"{d} m: {x:.2f}" for d, x in zip(mc["distance_m"], mc["pd"]))
        rows.append(f"| Monte Carlo UAV ({mc['trials']} random tracks per distance) | P_D vs distance | | {pd} | |")
    table = "\n".join(rows)
    readme = (ROOT / "README.md").read_text()
    block = f"<!-- RESULTS:BEGIN (generated by scripts/make_results_table.py) -->\n{table}\n<!-- RESULTS:END -->"
    if "RESULTS_TABLE_PLACEHOLDER" in readme:
        readme = readme.replace("RESULTS_TABLE_PLACEHOLDER", block)
    else:
        readme = re.sub(r"<!-- RESULTS:BEGIN.*?<!-- RESULTS:END -->", lambda _: block, readme, flags=re.S)
    (ROOT / "README.md").write_text(readme)
    print(table)

    # link budget + Monte Carlo summary in docs/theory.md, section 7
    rows = ["| Target (assumptions in `config/*.yaml`) | Echo power | SNR per sample | SNR after processing | Below direct path |",
            "|---|---|---|---|---|"]
    names = {"walker": "Indoor walker (0.5 m^2 torso + limbs, about 7 m)", "fan": "Indoor fan (0.02 m^2, about 3 m)",
             "room": "Indoor static clutter (sum)", "uav": "Outdoor UAV (0.028 m^2 incl. rotors, about 95 m)",
             "person": "Outdoor person (about 50 m)"}
    for sec in ("indoor", "outdoor"):
        for t, d in m[sec]["link_budget"]["targets"].items():
            if t in names:
                rows.append(f"| {names[t]} | {d['total_dbm']:.1f} dBm | {d['snr_per_sample_db']:.1f} dB | "
                            f"{d['snr_after_processing_db']:.1f} dB | {d['below_direct_path_db']:.1f} dB |")
    lb_i, lb_o = m["indoor"]["link_budget"], m["outdoor"]["link_budget"]
    sys.path.insert(0, str(ROOT))
    from isac.config import load_config
    cfg_i, cfg_o = load_config(ROOT / "config/indoor.yaml"), load_config(ROOT / "config/outdoor_uav.yaml")
    txt = "\n".join(rows) + (
        f"\n\nAssumed mean TX power (section 8): {cfg_i.tx_power_dbm:.0f} dBm indoors, {cfg_o.tx_power_dbm:.0f} dBm outdoors. "
        f"Direct path: {lb_i['direct_path_dbm']:.1f} dBm indoors, {lb_o['direct_path_dbm']:.1f} dBm outdoors. "
        "Indoors the clutter is stronger than the direct path and the system is limited by dynamic range "
        "(phase noise, ADC quantisation, residual direct-path variation), not by thermal noise.")
    if "monte_carlo_uav" in m:
        mc = m["monte_carlo_uav"]
        pd = ", ".join(f"{d} m: {x:.2f}" for d, x in zip(mc["distance_m"], mc["pd"]))
        diffs = [p_ - s_ for p_, s_, x in zip(mc["predicted_snr_db"], mc["median_snr_db"], mc["pd"]) if s_ is not None and x >= 0.5]
        txt += (f"\n\nMonte Carlo ({mc['trials']} random tracks per distance, `fig07_monte_carlo_uav.png`), detection "
                f"probability: {pd}. Where at least half the tracks are detected, the measured CFAR SNR is "
                f"{min(diffs):.1f} to {max(diffs):.1f} dB below the link-budget prediction (Hann windows, about 3.5 dB, "
                "plus straddle loss); where few tracks are detected, their SNR is biased upwards (selection bias).")
    th = (ROOT / "docs/theory.md").read_text()
    block = f"<!-- LINKBUDGET:BEGIN (generated by scripts/make_results_table.py) -->\n{txt}\n<!-- LINKBUDGET:END -->"
    th = re.sub(r"<!-- LINKBUDGET:BEGIN.*?<!-- LINKBUDGET:END -->", lambda _: block, th, flags=re.S)
    (ROOT / "docs/theory.md").write_text(th)


if __name__ == "__main__":
    main()
